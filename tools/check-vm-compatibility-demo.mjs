#!/usr/bin/env node
import assert from 'node:assert/strict';
import {mkdtemp,readFile,rm,readdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {recordCompatibilityDemo,program} from './generate-vm-compatibility-demo.mjs';
import vm from '../apps/research-ui/vm_semantics.js';
const expectedProgram=[1537,1809,3377,53,4099,4139,10769,2609,870,65313,135,24,61,580,29];
assert.deepEqual(program,expectedProgram,'Independent pinned instruction words');
const trace=recordCompatibilityDemo();
assert.deepEqual(trace.steps[0].before,{pc:0,halted:false,registers:[0,0,0,0,0],stack:[],memory:[...expectedProgram.map((word,address)=>[address,word]),[64,0]]},'Independent initial snapshot');
// Independent expected transitions derived from the reference ISA, not predict()
// or an output snapshot generated by the recorder under test.
const expected=[
 [1,[6,0,0,0,0],[],0,false], [2,[6,7,0,0,0],[],0,false],
 [3,[6,7,0,13,0],[],0,false], [13,[6,7,0,13,1],[4],0,false],
 [14,[42,7,0,13,1],[4],0,false], [4,[42,7,0,13,0],[],0,false],
 [5,[42,7,0,13,0],[],42,false], [6,[42,7,42,13,0],[],42,false],
 [7,[42,42,42,13,0],[],42,false], [8,[42,42,42,10,0],[],42,false],
 [10,[42,42,42,10,0],[],42,false], [11,[42,42,42,10,1],[42],42,false],
 [12,[42,42,42,10,0],[],42,false], [13,[42,42,42,10,0],[],42,true]
];
assert.equal(trace.steps.length,14);assert.equal(trace.identity.backend,'fixture');
assert.deepEqual(trace.steps.map(s=>s.before.pc),[0,1,2,3,13,14,4,5,6,7,8,10,11,12]);
for(const [i,step] of trace.steps.entries()){
 const [pc,registers,stack,data,halted]=expected[i];
 assert.deepEqual(step.after,{pc,registers,stack,halted,memory:[...expectedProgram.map((word,address)=>[address,word]),[64,data]]},`Golden transition ${i}`);
 assert.equal(step.opcode,Buffer.from([expectedProgram[step.before.pc]&255,expectedProgram[step.before.pc]>>8]).toString('hex'));
 if(i)assert.deepEqual(step.before,trace.steps[i-1].after);
}
assert.deepEqual(recordCompatibilityDemo(),trace,'Each recording must reset all state');
assert.deepEqual(vm.trace(vm.parse(JSON.stringify(trace))),trace);
const inferred=vm.inspect(trace);
assert(inferred.opcodes.some(row=>row.status==='inferred'&&row.candidates.includes('register_const')),'Import automatically infers matching bounded candidates without a hypothesis file');
assert(inferred.opcodes.some(row=>row.status==='unknown'),'Unsupported demo operations remain unknown');
const dir=await mkdtemp(join(tmpdir(),'reb-vm-compatibility-'));
try{
 const script=fileURLToPath(new URL('./generate-vm-compatibility-demo.mjs',import.meta.url));
 const help=spawnSync(process.execPath,[script,'--help'],{cwd:dir,encoding:'utf8'});assert.equal(help.status,0,help.stderr);assert.match(help.stdout,/Usage:/);assert.deepEqual(await readdir(dir),[],'Help must not create output');
 for(const args of [[],['--unknown'],['--help','ignored.json']]){const invalid=spawnSync(process.execPath,[script,...args],{cwd:dir,encoding:'utf8'});assert.notEqual(invalid.status,0);assert.deepEqual(await readdir(dir),[],'Invalid options must not create output');}
 const path=join(dir,'demo.json'),run=()=>spawnSync(process.execPath,['tools/generate-vm-compatibility-demo.mjs',path],{encoding:'utf8'});
 const first=run();assert.equal(first.status,0,first.stderr);const bytes=await readFile(path);assert.deepEqual(JSON.parse(bytes),trace);
 assert.notEqual(run().status,0,'CLI must refuse overwrite');assert.deepEqual(await readFile(path),bytes);
}finally{await rm(dir,{recursive:true,force:true});}
console.log('PASS 14 independently specified compatibility transitions, call/return, taken branch, stack, known memory, halt PC, exact raw words, fresh state and private no-overwrite trace export');
